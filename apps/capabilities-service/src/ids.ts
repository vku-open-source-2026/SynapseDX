/**
 * Identifier grammar.
 *
 * Dataset IDs are Tier-2 slugs. Record IDs are caller-owned opaque identifiers:
 * they are preserved exactly and validated against the Tier-1 SynapseBase
 * document-id grammar instead of being rewritten.
 */
import { apiError } from './errors';

/** Tier-1 SynapseBase document ids (`SynapseOne/apps/base-service/src/index.ts`). */
export const DOCUMENT_ID_RE = /^[A-Za-z0-9_@.:+-]{1,256}$/;
export const DATASET_SLUG_RE = /^[a-z0-9][a-z0-9-]{0,79}$/;
export const SEMVER_RE = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

export function slugifyDataset(value: unknown): string {
  return String(value ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);
}

/** Validate a caller-supplied record id; returns it unchanged. */
export function validateRecordId(value: unknown): string {
  const id = String(value ?? '');
  if (!id) throw apiError(400, 'invalid_record_id', 'record id must not be empty');
  if (id === '.' || id === '..' || /[\r\n/\\]/.test(id) || !DOCUMENT_ID_RE.test(id)) {
    throw apiError(400, 'invalid_record_id', 'record id must match [A-Za-z0-9_@.:+-]{1,256}');
  }
  return id;
}

/** Validate a dataset slug/id from the URL path. */
export function validateDatasetId(value: unknown): string {
  const id = String(value ?? '');
  if (!DATASET_SLUG_RE.test(id)) throw apiError(400, 'invalid_dataset_id', 'dataset id must be a lowercase slug');
  return id;
}

/** Datasource slugs are generated by Tier-2 and must fit the Tier-1 limit (64). */
export function datasourceSlug(datasetId: string, discriminator: string): string {
  const base = slugifyDataset(datasetId).slice(0, 40) || 'dataset';
  const suffix = discriminator.replace(/[^a-z0-9]/gi, '').toLowerCase().slice(0, 8) || '0';
  return `synapsedx-${base}-${suffix}`.slice(0, 64);
}

export function entityId(datasetSlug: string, recordId: string): string {
  return `urn:synapsedx:${datasetSlug}:${recordId}`;
}
